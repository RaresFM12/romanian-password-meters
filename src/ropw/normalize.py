import json
import unicodedata
from pathlib import Path
from .config import REPO_ROOT

FOLD = {
    "ă": "a", "â": "a", "î": "i", "ș": "s", "ț": "t", "ş": "s", "ţ": "t",
    "Ă": "A", "Â": "A", "Î": "I", "Ș": "S", "Ț": "T", "Ş": "S", "Ţ": "T",
}
CEDILLA = {"ș": "ş", "ț": "ţ", "Ș": "Ş", "Ț": "Ţ"}
COMMA = {"ş": "ș", "ţ": "ț", "Ş": "Ș", "Ţ": "Ț"}
DIGRAPH = {"ș": "sh", "ț": "tz", "Ș": "Sh", "Ț": "Tz"}

# pre-1993 rule: â stays â in words from "român"
ROMAN_FORMS = ["român", "Român", "ROMÂN"]
# private-use characters, never in real text
PLACEHOLDERS = ["\ue000", "\ue001", "\ue002"]


def nfc(s):
    return unicodedata.normalize("NFC", s)


def nfd(s):
    return unicodedata.normalize("NFD", s)


def to_ascii(s):
    out = ""
    for ch in nfc(s):
        out += FOLD.get(ch, ch)
    return out


fold = to_ascii


def to_comma(s):
    out = ""
    for ch in nfc(s):
        out += COMMA.get(ch, ch)
    return out


def to_cedilla(s):
    out = ""
    for ch in nfc(s):
        out += CEDILLA.get(ch, ch)
    return out


def to_digraph(s):
    out = ""
    for ch in nfc(s):
        if ch in DIGRAPH:
            out += DIGRAPH[ch]
        else:
            out += FOLD.get(ch, ch)
    return out


def to_pre1993(s):
    s = nfc(s)
    for form, ph in zip(ROMAN_FORMS, PLACEHOLDERS):
        s = s.replace(form, ph)
    s = s.replace("â", "î").replace("Â", "Î")
    for form, ph in zip(ROMAN_FORMS, PLACEHOLDERS):
        s = s.replace(ph, form)
    return s


def to_pre1993_ascii(s):
    return to_ascii(to_pre1993(s))


def export_tables(path=None):
    if path is None:
        path = REPO_ROOT / "packages/zxcvbn-ro-extended/src/tables.json"
    path = Path(path)
    data = {"_comment": "Generated by ropw.normalize.export_tables; do not edit by hand.",
            "fold": FOLD, "cedilla": CEDILLA, "digraph": DIGRAPH, "roman_stem": "român"}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


if __name__ == "__main__":
    print("wrote", export_tables())
