"""Romanian spelling normalisation and variant generation (guide C03).

This module is the single source of truth for the fold table and the spelling
variants of Table 4. The JavaScript side of the extension reads the same tables
from ``packages/zxcvbn-ro-extended/src/tables.json`` (written by ``export_tables``),
so Python and the meter never disagree.

Romanian diacritic letters and their code points:
    ă U+0103   â U+00E2   î U+00EE   ș U+0219   ț U+021B   (comma-below, correct)
    ş U+015F   ţ U+0163                                    (cedilla, legacy)
and their uppercase forms.
"""
from __future__ import annotations

import json
import unicodedata
from pathlib import Path

from .config import REPO_ROOT

# --- 1:1 fold to ASCII (comma-below and cedilla both fold to the same letter) --
FOLD: dict[str, str] = {
    "ă": "a", "â": "a", "î": "i", "ș": "s", "ț": "t", "ş": "s", "ţ": "t",
    "Ă": "A", "Â": "A", "Î": "I", "Ș": "S", "Ț": "T", "Ş": "S", "Ţ": "T",
}

# comma-below -> cedilla (legacy encoding); vowels are untouched
CEDILLA: dict[str, str] = {"ș": "ş", "ț": "ţ", "Ș": "Ş", "Ț": "Ţ"}

# comma-below -> sh / tz digraph; other diacritics are dropped by the fold
DIGRAPH: dict[str, str] = {"ș": "sh", "ț": "tz", "Ș": "Sh", "Ț": "Tz"}

# the "român" family keeps â under the pre-1993 rule
_ROMAN_STEM = "român"
_ROMAN_STEM_CAP = "Român"
_PH_LOWER = ""  # private-use placeholders, cannot occur in real text
_PH_CAP = ""


def nfc(s: str) -> str:
    """Unicode NFC (composed) form, as NIST SP 800-63B-4 recommends."""
    return unicodedata.normalize("NFC", s)


def nfd(s: str) -> str:
    """Unicode NFD (decomposed) form."""
    return unicodedata.normalize("NFD", s)


def to_ascii(s: str) -> str:
    """Fold every Romanian diacritic to its base letter (1:1, length-preserving)."""
    return "".join(FOLD.get(ch, ch) for ch in nfc(s))


# fold() is the name used by the meter side; it is the same 1:1 map.
fold = to_ascii


def to_cedilla(s: str) -> str:
    """Rewrite comma-below ș/ț as legacy cedilla ş/ţ."""
    return "".join(CEDILLA.get(ch, ch) for ch in nfc(s))


def to_digraph(s: str) -> str:
    """Rewrite ș/ț as sh/tz and drop the other diacritic signs."""
    out: list[str] = []
    for ch in nfc(s):
        if ch in DIGRAPH:
            out.append(DIGRAPH[ch])
        else:
            out.append(FOLD.get(ch, ch))
    return "".join(out)


def to_pre1993(s: str) -> str:
    """Rewrite interior â as î, keeping â in the ``român`` family (1993 rule)."""
    s = nfc(s)
    protected = s.replace(_ROMAN_STEM, _PH_LOWER).replace(_ROMAN_STEM_CAP, _PH_CAP)
    protected = protected.replace("â", "î").replace("Â", "Î")
    return protected.replace(_PH_LOWER, _ROMAN_STEM).replace(_PH_CAP, _ROMAN_STEM_CAP)


def to_pre1993_ascii(s: str) -> str:
    """Pre-1993 spelling, then folded to ASCII."""
    return to_ascii(to_pre1993(s))


def export_tables(path: str | Path | None = None) -> Path:
    """Write the fold and variant tables as JSON for the JavaScript side."""
    if path is None:
        path = REPO_ROOT / "packages/zxcvbn-ro-extended/src/tables.json"
    path = Path(path)
    payload = {
        "_comment": "Generated by ropw.normalize.export_tables; do not edit by hand.",
        "fold": FOLD,
        "cedilla": CEDILLA,
        "digraph": DIGRAPH,
        "roman_stem": _ROMAN_STEM,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    return path


if __name__ == "__main__":
    out = export_tables()
    print(f"wrote {out}")
